from odoo.tests.common import tagged

from .common import TAG, CampusCommon


@tagged('post_install', '-at_install')
class TestStudentLinks(CampusCommon):
    """The counters on the student form, and what their buttons open.

    A count that disagrees with the list behind it is worse than no count, so
    every test here checks the pair rather than the number alone.
    """

    def _locked_krs(self, year=None):
        """A study plan walked to Locked, which is what generates its KHS."""
        krs = self._make_krs(year=year or self.year)
        krs.action_submit()
        krs.action_approve()
        krs.action_lock()
        return krs

    # --- the numbers ------------------------------------------------------

    def test_a_student_with_nothing_yet_counts_zero(self):
        self.assertEqual(self.student.krs_count, 0)
        self.assertEqual(self.student.khs_count, 0)

    def test_the_study_plan_counter_follows_the_plans(self):
        self._make_krs()
        self.assertEqual(self.student.krs_count, 1)
        # schedule_retake, not schedule: a plan's lines must belong to the
        # same academic year as the plan, and the fixture keeps a separate
        # class for year_retake.
        self._make_krs(year=self.year_retake, schedules=self.schedule_retake)
        self.assertEqual(self.student.krs_count, 2)

    def test_the_transcript_counter_follows_the_locked_plans(self):
        """A transcript is generated by locking a plan, never typed in."""
        self.assertEqual(self.student.khs_count, 0)
        self._locked_krs()
        self.assertEqual(self.student.khs_count, 1)

    def test_an_ordinary_contact_counts_nothing(self):
        contact = self.env['res.partner'].create({'name': '%s Kontak' % TAG})
        self.assertEqual(contact.krs_count, 0)
        self.assertEqual(contact.khs_count, 0)

    # --- the buttons ------------------------------------------------------

    def test_the_study_plan_button_opens_exactly_what_it_counted(self):
        krs = self._make_krs()
        action = self.student.action_open_krs()
        self.assertEqual(action['res_model'], 'academic.krs')
        self.assertEqual(self.env['academic.krs'].search(action['domain']), krs)

    def test_the_transcript_button_opens_exactly_what_it_counted(self):
        self._locked_krs()
        action = self.student.action_open_khs()
        found = self.env['academic.khs'].search(action['domain'])
        self.assertEqual(found, self.student.khs_ids)

    def test_a_study_plan_may_be_created_from_here_with_the_student_filled_in(self):
        """A plan belongs to a student, and this is the one screen where that
        is already known."""
        context = self.student.action_open_krs()['context']
        self.assertEqual(context.get('default_student_id'), self.student.id)
        self.assertNotEqual(context.get('create'), False)

    def test_a_transcript_may_not_be_created_from_here(self):
        """It is generated from a locked plan in academic_krs.py. New here
        would make an empty one that no plan accounts for."""
        self.assertFalse(self.student.action_open_khs()['context'].get('create'))

    # --- the wiring -------------------------------------------------------

    def test_the_student_form_carries_the_button_box(self):
        """The standalone student form is written from scratch rather than
        inherited from base.view_partner_form, so it had no button box of its
        own - the div other partner forms carry had to be added by hand, and
        nothing else would notice if it went missing again."""
        arch = self.env['res.partner'].get_view(
            self.env.ref('campus_core.view_campus_student_form_standalone').id, 'form',
        )['arch']
        self.assertIn('button_box', arch)
        self.assertIn('krs_count', arch)
        self.assertIn('khs_count', arch)
